/**
 * Forma "a riga di database" di un annuncio: il venditore è una foreign key.
 * Il repository si occupa della join → `Listing`.
 */
export type ListingRecord = Omit<Listing, 'seller'> & { sellerId: string }

type ListingInput = Omit<
  ListingRecord,
  'sportId' | 'location' | 'model' | 'condition' | 'defects' | 'extraSpecs' | 'status' | 'quantity'
> &
  Partial<Pick<ListingRecord, 'model' | 'condition' | 'defects' | 'extraSpecs' | 'status' | 'quantity'>>

/** Valori di default e campi derivati (sport dalla sottocategoria, località dal venditore). */
function defineListing(input: ListingInput): ListingRecord {
  const seller = SELLER_RECORDS.find((record) => record.id === input.sellerId)
  if (!seller) throw new Error(`Venditore "${input.sellerId}" non trovato per l'annuncio "${input.id}"`)
  return {
    model: null,
    condition: null,
    defects: [],
    extraSpecs: [],
    status: 'disponibile',
    quantity: 1,
    ...input,
    sportId: getSubcategory(input.subcategoryId).sportId,
    location: seller.location,
  }
}

